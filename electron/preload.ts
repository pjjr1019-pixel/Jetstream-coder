import { contextBridge, ipcRenderer } from 'electron';
contextBridge.exposeInMainWorld('coder', {
  openProject: () => ipcRenderer.invoke('project:open'),
  getIgnorePatterns: () => ipcRenderer.invoke('project:ignore-get'),
  setIgnorePatterns: (patterns:string) => ipcRenderer.invoke('project:ignore-set',patterns),
  indexStatus: () => ipcRenderer.invoke('project:index-status'),
  rebuildIndex: () => ipcRenderer.invoke('project:index-rebuild'),
  listFiles: () => ipcRenderer.invoke('project:files'),
  createFolder: (name:string) => ipcRenderer.invoke('project:create-folder',name),
  createFile: (name:string) => ipcRenderer.invoke('project:create-file',name),
  readFile: (name:string) => ipcRenderer.invoke('project:read',name),
  saveFile: (name:string, content:string, fingerprint:string) => ipcRenderer.invoke('project:save',name,content,fingerprint),
  searchSymbols: (query:string) => ipcRenderer.invoke('project:symbols',query),
  search: (query:string) => ipcRenderer.invoke('project:search',query),
  terminalStart: () => ipcRenderer.invoke('terminal:start'),
  terminalWrite: (text:string) => ipcRenderer.invoke('terminal:write',text),
  terminalResize: (cols:number,rows:number) => ipcRenderer.invoke('terminal:resize',cols,rows),
  terminalStop: () => ipcRenderer.invoke('terminal:stop'),
  onTerminalData: (cb:(text:string)=>void) => {const f=(_event:Electron.IpcRendererEvent,text:string)=>cb(text);ipcRenderer.on('terminal:data',f);return ()=>ipcRenderer.removeListener('terminal:data',f)},
  onTerminalExit: (cb:(code:number)=>void) => {const f=(_event:Electron.IpcRendererEvent,code:number)=>cb(code);ipcRenderer.on('terminal:exit',f);return ()=>ipcRenderer.removeListener('terminal:exit',f)},
  terminalRun: (command:string) => ipcRenderer.invoke('terminal:run',command),
  onProjectChanged: (cb:()=>void) => ipcRenderer.on('project:changed',cb),
  gitChanges: () => ipcRenderer.invoke('project:git-changes'),
  gitStageDeletion: (name:string) => ipcRenderer.invoke('project:git-stage-deletion',name),
  gitFileDiff: (name:string) => ipcRenderer.invoke('project:git-file-diff',name),
  gitUnstage: (name:string) => ipcRenderer.invoke('project:git-unstage',name),
  gitStage: (name:string,fingerprint:string) => ipcRenderer.invoke('project:git-stage',name,fingerprint),
  gitCommitPreview: () => ipcRenderer.invoke('project:git-commit-preview'),
  gitCommit: (message:string,tree:string,head:string,headRef:string) => ipcRenderer.invoke('project:git-commit',message,tree,head,headRef),
  gitHistory: () => ipcRenderer.invoke('project:git-history'),
  gitDiff: () => ipcRenderer.invoke('project:git-diff'),
  gitStatus: () => ipcRenderer.invoke('project:git'),
  jobs: (query:string='') => ipcRenderer.invoke('jobs:list',query),
  requeueJob: (id:number) => ipcRenderer.invoke('jobs:requeue',id),
  cancelJob: (id:number) => ipcRenderer.invoke('jobs:cancel',id),
  addJob: (request:string) => ipcRenderer.invoke('jobs:add',request),
  prepareScratch: (id:number) => ipcRenderer.invoke('jobs:scratch',id),
  openScratch: (id:number) => ipcRenderer.invoke('jobs:open-scratch',id),
  scratchConflicts: (id:number) => ipcRenderer.invoke('jobs:conflicts',id),
  scratchDiff: (id:number) => ipcRenderer.invoke('jobs:diff',id),
  latestCandidate: (id:number) => ipcRenderer.invoke('jobs:latest-candidate',id),
  candidateDiff: (id:number) => ipcRenderer.invoke('jobs:candidate-diff',id),
  candidateEvidence: (id:number) => ipcRenderer.invoke('jobs:candidate-evidence',id),
  rejectCandidate: (id:number) => ipcRenderer.invoke('jobs:reject-candidate',id),
  approveCandidate: (id:number,source:string,candidate:string,review:number,check:number) => ipcRenderer.invoke('jobs:approve-candidate',id,source,candidate,review,check),
  openCandidate: (id:number) => ipcRenderer.invoke('jobs:open-candidate',id),
  verificationConfig: () => ipcRenderer.invoke('verification:config'),
  configureVerification: (build:string,test:string) => ipcRenderer.invoke('verification:configure',build,test),
  verifyJob: (id:number,candidateId?:number) => ipcRenderer.invoke('verification:run',id,candidateId),
  jobGate: (id:number) => ipcRenderer.invoke('jobs:gate',id),
  jobHistory: (id:number) => ipcRenderer.invoke('jobs:history',id),
  setPause: (paused:boolean) => ipcRenderer.invoke('jobs:pause',paused),
  localUsage: () => ipcRenderer.invoke('providers:local-usage'),
  askLocal: (model:string,prompt:string) => ipcRenderer.invoke('ollama:ask',model,prompt),
  proposeLocal: (id:number,model:string,name:string) => ipcRenderer.invoke('ollama:propose',id,model,name),
  latestProposal: (id:number) => ipcRenderer.invoke('ollama:latest-proposal',id),
  reviewProposal: (id:number,model:string) => ipcRenderer.invoke('ollama:review-proposal',id,model),
  cancelLocal: () => ipcRenderer.invoke('ollama:cancel'),
  providers: () => ipcRenderer.invoke('providers:list'),
  onCloseRequested: (cb:()=>void) => ipcRenderer.on('close:request',cb),
  confirmClose: () => ipcRenderer.send('close:confirm'),
});
